"""
prompt_schemas.py — Pydantic request and response contracts for AutoPrompt API.
"""

from __future__ import annotations

from typing import Literal, Optional
from pydantic import BaseModel, Field, field_validator


class GenerateRequest(BaseModel):
    """Payload contract for POST /api/generate"""
    user_idea: str = Field(
        ...,
        min_length=3,
        max_length=10000,
        description="The core task or prompt idea to generate.",
        examples=["Create a prompt for analyzing customer churn in Python."],
    )
    mode: Literal["quick", "advanced"] = Field(
        default="quick",
        description="Generation mode: quick (task only) or advanced (with role, context, etc.)",
    )
    category: Optional[str] = Field(
        default=None,
        max_length=100,
        description="Optional domain category (e.g., Programming, Data Science).",
        examples=["Data Science"],
    )
    role: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Optional role or persona (advanced mode).",
        examples=["Senior Data Scientist"],
    )
    objective: Optional[str] = Field(
        default=None,
        max_length=1000,
        description="Optional explicit goal (advanced mode).",
        examples=["Build an end-to-end churn classification pipeline."],
    )
    context: Optional[str] = Field(
        default=None,
        max_length=3000,
        description="Optional background or constraints context (advanced mode).",
        examples=["Telecommunications dataset with 10k rows and class imbalance."],
    )
    constraints: Optional[str] = Field(
        default=None,
        max_length=1500,
        description="Optional constraints or limitations (advanced mode).",
        examples=["Use scikit-learn and xgboost; do not leak test data."],
    )
    output_format: Optional[str] = Field(
        default=None,
        max_length=1000,
        description="Optional expected output format (advanced mode).",
        examples=["Modular Python code and a markdown comparison table."],
    )

    @field_validator("user_idea")
    @classmethod
    def validate_user_idea_not_blank(cls, v: str) -> str:
        trimmed = v.strip()
        if len(trimmed) < 3:
            raise ValueError("user_idea cannot be blank or shorter than 3 non-whitespace characters.")
        return trimmed


class GenerateResponse(BaseModel):
    """Response contract for POST /api/generate"""
    success: bool = Field(..., description="True if generation succeeded.")
    model: str = Field(..., description="Model name used for generation.")
    generated_prompt: Optional[str] = Field(
        default=None,
        description="The fully structured prompt generated by the model.",
    )
    input_tokens: int = Field(default=0, description="Tokens in the input prompt request.")
    output_tokens: int = Field(default=0, description="Tokens in the generated prompt.")
    response_time_ms: int = Field(default=0, description="Execution time in milliseconds.")
    error_code: Optional[str] = Field(default=None, description="Safe error category if failed.")
    error_message: Optional[str] = Field(default=None, description="Human-readable safe error message.")


class OptimizeRequest(BaseModel):
    """Payload contract for POST /api/optimize"""
    original_prompt: str = Field(
        ...,
        min_length=3,
        max_length=15000,
        description="The raw, unoptimized prompt to refine.",
        examples=["Analyze my data and tell me why customers leave."],
    )
    mode: Literal["quick", "advanced"] = Field(
        default="quick",
        description="Optimization mode: quick (streamlined) or advanced (deep structure).",
    )
    optimization_instructions: Optional[str] = Field(
        default=None,
        max_length=2000,
        description="Optional custom refinement instructions.",
        examples=["Focus on technical precision and eliminate all fluff."],
    )

    @field_validator("original_prompt")
    @classmethod
    def validate_original_prompt_not_blank(cls, v: str) -> str:
        trimmed = v.strip()
        if len(trimmed) < 3:
            raise ValueError("original_prompt cannot be blank or shorter than 3 non-whitespace characters.")
        return trimmed


class OptimizeResponse(BaseModel):
    """Response contract for POST /api/optimize"""
    success: bool = Field(..., description="True if optimization succeeded.")
    model: str = Field(..., description="Model name used for optimization.")
    original_prompt: str = Field(..., description="The original submitted prompt.")
    optimized_prompt: Optional[str] = Field(
        default=None,
        description="The optimized, structured prompt.",
    )
    original_tokens: int = Field(default=0, description="Tokens in the original input prompt.")
    optimized_tokens: int = Field(default=0, description="Tokens in the optimized prompt.")
    tokens_saved: int = Field(
        default=0,
        description="original_tokens minus optimized_tokens. Can be negative if structure expanded.",
    )
    reduction_percentage: float = Field(
        default=0.0,
        description="Percentage token reduction. Negative if prompt length expanded for clarity.",
    )
    response_time_ms: int = Field(default=0, description="Execution time in milliseconds.")
    error_code: Optional[str] = Field(default=None, description="Safe error category if failed.")
    error_message: Optional[str] = Field(default=None, description="Human-readable safe error message.")


class TokenCountRequest(BaseModel):
    """Payload contract for POST /api/count-tokens"""
    text: str = Field(
        ...,
        min_length=1,
        max_length=50000,
        description="Text content to count tokens for.",
        examples=["Hello Gemini, count my tokens."],
    )

    @field_validator("text")
    @classmethod
    def validate_text_not_blank(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("text cannot be blank.")
        return trimmed


class TokenCountResponse(BaseModel):
    """Response contract for POST /api/count-tokens"""
    success: bool = Field(..., description="True if token count was successfully computed.")
    token_count: int = Field(..., description="Official token count returned by Gemini.")
    model: str = Field(..., description="Model used for tokenization.")
    error_code: Optional[str] = Field(default=None, description="Safe error category if failed.")
    error_message: Optional[str] = Field(default=None, description="Human-readable safe error message.")
